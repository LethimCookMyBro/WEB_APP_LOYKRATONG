// Downloads stroke-order SVG data from KanjiVG (CC BY-SA 3.0, Ulrich Apel)
// and writes a compact ES module: public/js/data/stroke-data-ja.js
// Usage: node scripts/build-stroke-data.mjs
import { writeFile } from 'node:fs/promises';

const BASE = 'https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/';
const chars = new Set();
for (let c = 0x3041; c <= 0x3093; c++) chars.add(String.fromCodePoint(c)); // hiragana
for (let c = 0x30a1; c <= 0x30f6; c++) chars.add(String.fromCodePoint(c)); // katakana
chars.add('ー');
// Kanji used in the wish library (language-data.js)
for (const ch of '研究早終勉強健康幸成功') chars.add(ch);

const hex = (ch) => ch.codePointAt(0).toString(16).padStart(5, '0');
const out = {};
const missing = [];

async function fetchOne(ch) {
  const res = await fetch(BASE + hex(ch) + '.svg');
  if (!res.ok) { missing.push(ch); return; }
  const svg = await res.text();
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  const nums = [...svg.matchAll(/matrix\(1 0 0 1 ([\d.\-]+) ([\d.\-]+)\)">(\d+)</g)]
    .map((m) => [Number(m[1]), Number(m[2])]);
  if (!paths.length) { missing.push(ch); return; }
  out[ch] = { s: paths, n: nums };
}

const list = [...chars];
for (let i = 0; i < list.length; i += 12) {
  await Promise.all(list.slice(i, i + 12).map(fetchOne));
}

const header = `// AUTO-GENERATED by scripts/build-stroke-data.mjs — do not edit by hand.
// Stroke-order data from KanjiVG (https://kanjivg.tagaini.net)
// Copyright (C) 2009-2011 Ulrich Apel. Licensed under CC BY-SA 3.0
// (https://creativecommons.org/licenses/by-sa/3.0/). This derived file is
// distributed under the same license. viewBox is 0 0 109 109.
`;
await writeFile(new URL('../public/js/data/stroke-data-ja.js', import.meta.url),
  header + 'export const STROKES = ' + JSON.stringify(out) + ';\n');
console.log('chars:', Object.keys(out).length, 'missing:', missing.join(''));
